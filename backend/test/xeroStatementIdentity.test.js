const test=require('node:test');
const assert=require('node:assert/strict');
const {identityFor,matchesCandidate,identitySql}=require('../src/utils/xeroStatementIdentity');
const bank=extra=>({direction:'received',...extra});
test('amount-only is allowed only without usable identity; named failures never broaden',()=>{
  assert.equal(identityFor(bank({})).mode,'amount_only');
  assert.equal(identityFor(bank({payee:'Rent'})).mode,'amount_only');
  const p=identityFor(bank({description:'/ORDP/MAHESWARI RHEA/BREF/123/REMI/November rent'}));
  assert.equal(p.mode,'name');
  assert.ok(matchesCandidate(p,{tenant_name:'Rhea Maheswari'}));
  assert.ok(!matchesCandidate(p,{tenant_name:'Jo Ann'}));
  assert.equal(identityFor(bank({description:'/ORDP/MAHESWARI...' })).mode,'identity_unreadable');
  assert.equal(identityFor(bank({payee:'Rhea Maheswari',description:'/ORDP/Other Person/BREF/123'})).mode,'identity_conflict');
  assert.equal(identityFor(bank({payee:'Rhea Maheswari',description:'/ORDP/MAHESWARI RHEA/BREF/123'})).mode,'name');
});
test('name and business reference must both match; outgoing sender is not beneficiary',()=>{
  const p=identityFor(bank({payee:'Ms. Rhea Maheswari',reference:'TRIV-35671'}));
  assert.equal(p.mode,'name_and_reference');
  assert.ok(matchesCandidate(p,{tenant_name:'Rhea Maheswari',code:'TRIV35671'}));
  assert.ok(!matchesCandidate(p,{tenant_name:'Other Person',code:'TRIV35671'}));
  assert.ok(!matchesCandidate(p,{tenant_name:'Rhea Maheswari',code:'TRIV35672'}));
  assert.equal(identityFor(bank({direction:'spent',description:'/ORDP/Own Company/BREF/123'})).payee,null);
  assert.equal(identityFor(bank({direction:'spent',description:'/BENM/Other Person/BREF/123'})).payee,'Other Person');
  const ref=identityFor(bank({reference:'ABC-123456'}));
  assert.ok(matchesCandidate(ref,{note:'Receipt ABC-123456 received'}));
  assert.ok(!matchesCandidate(ref,{note:'Receipt ZABC1234567'}));
  assert.match(identitySql(p,{names:['t.name'],references:['i.code']}).sql,/ AND /);
});
test('processor deposits use remittance name words and reject unrelated names', () => {
  const description = '/ORDP/VISA PAYMENTS LIMITED/BREF/123/REMI/Hazel Morton,T X12345';
  const policy = identityFor(bank({ description }));
  assert.equal(policy.payee, 'Hazel Morton');
  assert.equal(policy.name_source, 'remittance');
  assert.ok(matchesCandidate(policy, { tenant_name: 'Morton Hazel' }));
  assert.ok(matchesCandidate(policy, { tenant_name: 'Hazel Louise Morton' }));
  assert.ok(!matchesCandidate(policy, { tenant_name: 'Hazel Joseph' }));
  assert.ok(!matchesCandidate(policy, { tenant_name: 'Hazel Mortonson' }));
  assert.equal(identityFor(bank({ description, payee: 'Jane Other' })).mode, 'identity_conflict');
  assert.equal(identityFor(bank({ description: '/ORDP/Wise Payments Hong Kong Limited/REMI/November rent' })).name_source, null);
  assert.equal(identityFor(bank({ description: '/ORDP/Another Person/REMI/Hazel Morton,T X12345' })).payee, 'Another Person');
  const gate = identitySql(policy, { names: ['t.name'], contentName: 'm.content' });
  assert.match(gate.sql, /REGEXP_LIKE/);
  assert.ok(gate.params.includes('(^|[^[:alnum:]])morton([^[:alnum:]]|$)'));
});

test('partial payer names require three whole words, allow reordering, and remain invoice-only', () => {
  const policy = identityFor(bank({payee:'G, LIM TIM JIA LIAN'}));
  const candidate = {kind:'invoice',tenant_name:'Tim Lim Jia Liang',code:'TRIV12345'};
  assert.ok(matchesCandidate(policy,candidate));
  assert.ok(!matchesCandidate(policy,{...candidate,kind:'lease'}));
  assert.ok(!matchesCandidate(policy,{...candidate,_identity_company:true}));
  assert.ok(!matchesCandidate(policy,{...candidate,tenant_name:'Tim Lim Jian Liang'}));
  assert.ok(!matchesCandidate(policy,{...candidate,tenant_name:'Tim Tim Lim Liang'}));
  assert.ok(!matchesCandidate(policy,{...candidate,tenant_name:'Tim Lim Jia Other Extra'}));
  assert.ok(!matchesCandidate(identityFor(bank({payee:'Tim Lim Jia Lian',direction:'spent'})),candidate));
  assert.ok(!matchesCandidate(identityFor(bank({payee:'G, LIM TIM JIA LIAN',reference:'TRIV12346'})),candidate));
  const gate=identitySql(policy,{names:['t.name'],partialName:'t.name'});
  assert.match(gate.sql,/>= 3/);
  assert.ok(gate.params.includes('(^|[^[:alnum:]])jia([^[:alnum:]]|$)'));
  assert.doesNotMatch(identitySql(policy,{names:['t.name']}).sql,/>= 3/);
});
